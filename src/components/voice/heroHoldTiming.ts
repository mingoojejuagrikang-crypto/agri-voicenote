/** 🔴 V-FIX3(리뷰 U11) — `prefers-reduced-motion: reduce`에서 진행 표현을 **저빈도 계단**으로.
 *
 *  종전에는 reduce에서도 홀드 내내 rAF로 매 프레임 진행바를 밀었다. 이 화면의 다른 모션은 전부
 *  reduce를 존중하는데(`StateDots`는 rAF를 아예 안 돌리고 `ChipZone`은 왕복을 끈다) **신규
 *  진행바만 60fps로 움직여** 그 계약을 혼자 깼다.
 *
 *  🔑 **홀드 시간 판정은 건드리지 않는다** — 홀드 길이는 그대로다. 바뀌는 것은 «몇 번
 *  그리는가»뿐이다: rAF(≈120회) → `REDUCED_STEP_MS` 간격 타이머(4회)로 4칸 계단. 진행 피드백은
 *  남고(민구가 요구한 «진행바»의 목적) 연속 애니메이션만 사라진다.
 *  ⚠️ 「그냥 안 그리기」는 고르지 않았다 — 위치 기반 진입에서 피드백이 사라지면 *"왜 안 꺼지지"*
 *  가 된다(BlackoutOverlay의 차오르는 원이 사양의 절반이었던 것과 같은 이유). */
export const REDUCED_STEPS = 4;

/** 🔴 v0.51 H2 — **파생 상수다. 숫자를 박지 마라.**
 *
 *  종전 값은 `750`(= 3000/4)이었고, `HOLD_TO_BLACKOUT_MS`가 2000으로 바뀌면 **나누어떨어지지
 *  않는다**: 틱이 750 / 1500 / 2000에 떨어져 진행값이 0 → 0.25(750ms) → 0.75(1500ms) → 1로
 *  뛴다. 즉 **홀드의 앞 37.5% 동안 진행바가 0에 머물다** 건너뛴다.
 *  🔴 그리고 이건 **`prefers-reduced-motion: reduce` 사용자에게만 보이는 회귀**라
 *  일반 점검으로는 **안 잡힌다.** 상수 하나가 조용히 남는 종류의 결함이다.
 *  🟢 정답 형태가 옆 파일에 이미 있었다 — `BlackoutOverlay`의
 *  `RELEASE_STEP_MS = HOLD_TO_WAKE_MS / RELEASE_STEPS`. 같은 방식으로 파생시킨다.
 *  ⚠️ 아래 `tick`의 계단 스냅도 같은 `REDUCED_STEPS`를 읽는다 — 종전에는 `Math.round(p*4)/4`로
 *  **4가 두 번 박혀 있었다**(칸 수를 바꾸면 한쪽만 고칠 수 있는 형태). */
export const REDUCED_STEP_MS = HOLD_TO_BLACKOUT_MS / REDUCED_STEPS;

/** 🔴 v0.51 H7′ — **짧은 `pointerup` 유예 창(ms).**
 *
 *  ## 무엇을 고치는가 — 증명된 기전에 대한 유일한 직접 처방
 *  민구 제보: *"진행바가 0으로 갔다가 **저절로** 다시 차오른다."*
 *  `setProgress` 호출 지점 전수(4개)로 그 현상의 경로가 **하나뿐**임이 증명됐다:
 *  「0으로 감」=`stopHold` · 「다시 차오름」=`beginHold`의 `schedule()`. 그리고 `beginHold`는
 *  `onPointerDown`으로만 불린다. ⇒ **`pointerup`(또는 cancel) → `pointerdown` 왕복이 실제로
 *  일어났다.** 민구가 «엄지 하나만» 닿았다고 했으므로 그 왕복은 **엄지 자신의 것**이다.
 *  👉 그래서 up을 유예 대상에서 빼면 **이 결함에 처방이 하나도 남지 않는다.**
 *
 *  ## 🔴 값은 **미실측 첫 시도값이다** — 확정값처럼 읽지 마라
 *  정전식 접촉 끊김은 통상 수십 ms, 의도적 뗌은 통상 200ms+. 그 사이를 잡는 첫 후보가 120ms다.
 *  **실기기 실측으로 조정해야 한다.**
 *  🔴 **반증 조건:** T를 150ms로 올려도 리셋이 계속되면 끊김이 그보다 길다는 뜻 →
 *  접촉 문제가 아니라 다른 축(X2 — iOS가 `pointercancel` 뒤 새 `pointerdown`을 발행)이고,
 *  그때는 **H7′를 되돌린다.** (그래서 이 변경은 독립 커밋이어야 한다.)
 *
 *  ## 대가 — 「뗐다」와 「끊겼다」를 **시간·거리로만** 가른다
 *  T가 크면 **손을 뗀 사용자의 홀드가 완주해 화면이 꺼진다.** 그 대가를 줄이는 두 축이
 *  **둘 다 필요**하다: ㉠ T를 작게 ㉡ 재접촉이 **직전 좌표 근처**일 때만(아래 반경). */
export const HOLD_GRACE_MS = 120;

/** 🔴 v0.51 H7′ — **유예가 대신 채워 준 시간의 총합 상한(ms).** 한 홀드 안에서 누적된다.
 *
 *  ## 왜 생겼나 — 독립 콜드 리뷰 [P1-1] (2026-08-31)
 *  H7′ 초안에는 **재개에 아무 상한이 없었다.** 「간격 < T · 거리 < R」만 지키면 조각 개수에도
 *  총 시간에도 제한이 없어서, 리뷰어가 **100ms 접촉 / 40ms 간격 × 25회**로 3,592ms 만에
 *  화면을 끄는 것을 실증했다(`resume=grace` 19건이 사슬로 이어졌다). 빌더도 독립 재현했다.
 *  🔴 **H7′가 만든 회귀다** — 이전에는 `stopHold`가 즉시 `setProgress(0)`을 해서 구조적으로
 *  불가능했다. **H2(3000→2000)를 되돌려도 사라지지 않는다**(H2는 필요한 조각 수를 줄일 뿐).
 *
 *  ## 🔴 왜 축이 「횟수」가 아니라 「시간」인가 — 이게 이 상수의 핵심 논거다
 *  흡수하려는 신호(떨리는 엄지)와 악용 경로(연타)가 **같은 입력**이라 상한을 잘못 잡으면
 *  **원래 고치려던 것을 못 고친다.** 둘을 실제로 가르는 것은 **듀티비**다:
 *    · 떨리는 엄지 — 접촉이 **길고**(수백 ms~) 끊김이 **짧다**(수십 ms). 끊김 누계가 작다.
 *    · 연타 — 접촉이 짧고 간격이 그만큼 길다. **끊김 누계가 크다.**
 *  👉 그래서 **「유예가 사실이 아닌 것으로 채운 시간」의 총합**을 직접 묶는다.
 *     이 값은 H7′가 하는 **거짓말의 총량**이고, 그걸 바운드하는 것이 가장 정직한 상한이다.
 *  🔴 **재개 횟수 상한을 기본으로 고르지 않은 이유:** 「엄지가 한 홀드에 몇 번 끊기는가」는
 *     **아직 아무도 모르는 값**이고, 그걸 재려고 H3(`resume=grace` 계수)를 넣은 것이다.
 *     지금 횟수를 박으면 **측정하려는 그 값을 추측으로 고정**하는 것이 되고, 너무 낮으면
 *     H7′가 조용히 무효가 된 채 로그에는 *"H7′가 안 먹었다"* 로 보인다 — 민구의 되돌리기
 *     판단이 정확히 그 비율로 내려지므로 **가장 나쁜 실패 모드**다.
 *
 *  ## 300ms의 산술 (🔴 **미실측 첫 시도값**이다 — T·R과 같은 지위)
 *    · 리뷰어 연타(간격 40ms): 7번째 재개에서 예산 소진 → 조립 가능 누계 **≈800ms < 2000** ⇒ 차단
 *    · 사람의 의도적 재탭 간격은 통상 **80ms+** → 재개 3회면 소진 ⇒ 조립 불가
 *    · 떨리는 엄지(끊김 20~40ms): **7~15회**까지 흡수 ⇒ 처방은 산다
 *  ⚠️ 실기기 로그의 `resume=grace` 분포를 보고 조정하라. **이 값이 처방의 생사를 정한다.**
 *  🔴 민구 확인 대기 — 대안(횟수 상한 · 진행 차감)과 대가는 `_ASK-build.md` Q4. */
